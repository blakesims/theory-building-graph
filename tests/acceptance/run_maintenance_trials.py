def stream_metrics(stdout):
    messages=[]
    for line in stdout.splitlines():
        try:messages.append(json.loads(line))
        except ValueError:continue
    results=[m for m in messages if m.get('type')=='result']
    tools={};errors=[]
    for m in messages:
        content=(m.get('message') or {}).get('content',m.get('content',[]))
        if not isinstance(content,list):continue
        for block in content:
            if block.get('type')=='tool_use':tools[block.get('id',json.dumps(block,sort_keys=True))]=block.get('name')
            if block.get('type')=='tool_result' and block.get('is_error'):errors.append(block.get('tool_use_id'))
    return {'tool_call_count':len(tools),'tools':list(tools.values()),'tool_error_ids':sorted(set(errors)),
            'result':results[-1] if results else None,'message_count':len(messages),
            'tool_metrics_available':any(m.get('type') in ('assistant','user') for m in messages)}


def run(out,arm,command):
    if not isinstance(command,list) or not command or not all(isinstance(x,str) for x in command):raise ValueError('command-json must be an argv string array')
    receipt_path=out/'control'/(arm+'-run.json')
    if receipt_path.exists():raise ValueError('Run already exists; prepare a fresh pair for repetition')
    prompt=(out/arm/'TASK.md').read_text();start=time.monotonic()
    timed_out=False
    try:
        completed=subprocess.run(command,input=prompt,text=True,capture_output=True,cwd=out/arm,timeout=360)
    except subprocess.TimeoutExpired as exc:
        timed_out=True
        def decoded(value):return value.decode(errors='replace') if isinstance(value,bytes) else value or ''
        completed=subprocess.CompletedProcess(command,124,decoded(exc.stdout),decoded(exc.stderr))
    metrics=stream_metrics(completed.stdout)
    (out/'control'/(arm+'-stdout.jsonl')).write_text(completed.stdout)
    receipt={'arm':arm,'command':command,'elapsed_seconds':round(time.monotonic()-start,3),'exit_code':completed.returncode,'stderr':completed.stderr,
             'timed_out':timed_out,'budget':{'tool_limit':20,'seconds_limit':300,'tool_limit_exceeded':metrics['tool_call_count']>20 if metrics['tool_metrics_available'] else None,'time_limit_exceeded':time.monotonic()-start>300},
             'prompt_bytes':len(prompt.encode()),'prompt_sha256':sha(prompt.encode()),'usage':(metrics.get('result') or {}).get('usage'),
             **metrics,'maintenance_work_observed':bool(metrics['tool_call_count']),'scope':'Actual participant tool calls and isolated store edits; quality still needs independent semantic grading.'}
    write_json(receipt_path,receipt)
    print(json.dumps({'completed':arm,'elapsed_seconds':receipt['elapsed_seconds'],'tool_calls':metrics['tool_call_count'],'exit_code':completed.returncode}))


