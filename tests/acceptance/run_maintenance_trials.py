def parse_prose(text):
    nodes={}
    for match in re.finditer(r'^## ([^\n]+)\n(.*?)(?=^## |\Z)',text,re.M|re.S):
        nid,body=match.groups();fields={}
        for key,value in re.findall(r'^(Type|Standing|Currency|Depends on|Subjects|Source|Text|Rationale): (.*)$',body,re.M):fields[key]=value
        nodes[nid.strip()]={'type':fields.get('Type'),'status':fields.get('Standing'),'text':fields.get('Text'),'meta':{'review_state':fields.get('Currency'),'rationale':fields.get('Rationale'),'source_ref':fields.get('Source')},'depends':[] if fields.get('Depends on')=='(none)' else [v.strip() for v in fields.get('Depends on','').split(',') if v.strip()]}
    return nodes


