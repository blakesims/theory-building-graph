def render_prose(model):
    lines=['# Versioned theory store','', 'All material in this fixture is synthetic. Stable headings and labeled fields permit unambiguous reference. Dependencies are explicit; subject links alone do not imply dependence.','']
    for nid,n in model['nodes'].items():
        if n['type']=='source':continue
        meta=n.get('meta',{});deps=sorted(e['to'] for e in model['edges'].values() if e['from']==nid and e['type']=='depends-on')
        subjects=sorted(e['to'] for e in model['edges'].values() if e['from']==nid and e['type'] in ('about','governs'))
        lines += [f'## {nid}',f"Type: {n['type']}",f"Standing: {n.get('status','declared')}",f"Currency: {meta.get('review_state','current')}",f"Depends on: {', '.join(deps) or '(none)'}",f"Subjects: {', '.join(subjects) or '(none)'}",f"Source: {meta.get('source_ref','(none)')}",f"Text: {n['text']}",f"Rationale: {meta.get('rationale','(none)')}", '']
    return '\n'.join(lines)


