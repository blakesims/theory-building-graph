def initial_graph():
    model={'version':1,'revision':0,'node_types':{k:{} for k in ['entity','operation','claim','question','source']},
           'edge_types':{k:{} for k in ['depends-on','about','governs','answers','revises']},'nodes':{},'edges':{},'changes':[]}
    for nid,text in [('steward-role','Steward role'),('orchestrator-role','Orchestrator role'),('recovery-role','Recovery coordinator role'),('intention','Intention'),('interface','Interface')]:
        model['nodes'][nid]={'type':'entity','text':text,'meta':{'kind':'agent-role' if nid.endswith('role') else 'object'}}
    model['nodes']['choose-work']={'type':'operation','text':'Select the next attempt to pursue an intention.'}
    for nid,text,rationale,source,deps in facts():
        model['nodes'][nid]={'type':'claim','text':text.strip(),'status':'accepted','meta':{'review_state':'current','rationale':rationale,'source_ref':source}}
        target='choose-work' if nid in ['C01','C02','C03','C04','C05'] else 'interface'
        model['edges'][nid+'-subject']={'type':'governs' if target=='choose-work' else 'about','from':nid,'to':target}
        for dep in deps:model['edges'][nid+'-depends-'+dep]={'type':'depends-on','from':nid,'to':dep,'requires':['accepted']}
    for nid,text in [('Q01','Must the orchestrator ask the operator before stopping a degraded attempt?'),('Q02','Which arbitrary cancellation outcomes should wake the steward?')]:
        model['nodes'][nid]={'type':'question','text':text,'status':'open','answer_shape':'condition','meta':{'review_state':'current','source_ref':'S03'}}
        model['edges'][nid+'-subject']={'type':'about','from':nid,'to':'orchestrator-role' if nid=='Q01' else 'intention'}
    for nid,text in sources().items():model['nodes'][nid]={'type':'source','text':text,'meta':{'synthetic':True,'source_kind':'synthetic-user-source'}}
    return model


